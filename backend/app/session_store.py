"""Thread-safe-by-session in-memory storage for ActionVani session state."""

from __future__ import annotations

import asyncio
import copy
import secrets
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from typing import Any

from app.session_models import (
    PendingConfirmation,
    SessionState,
    SessionStatus,
    SessionUpdate,
    validate_application_draft,
)


class SessionStoreError(Exception):
    """Base error raised by the session store."""


class SessionNotFoundError(SessionStoreError):
    """Raised when an update targets an unknown or expired session."""


class SessionConflictError(SessionStoreError):
    """Raised when an update uses a stale revision or conflicts with state."""


Clock = Callable[[], datetime]
DEFAULT_IDLE_TIMEOUT = timedelta(minutes=30)


@dataclass
class _SessionEntry:
    """Private runtime data; locks are deliberately not part of SessionState."""

    state: SessionState
    lock: asyncio.Lock = field(default_factory=asyncio.Lock)


class InMemorySessionStore:
    """Store independent session snapshots in memory for one backend process."""

    def __init__(
        self,
        idle_timeout: timedelta = DEFAULT_IDLE_TIMEOUT,
        *,
        clock: Clock | None = None,
    ) -> None:
        if idle_timeout <= timedelta(0):
            raise ValueError("idle_timeout must be greater than zero")
        self._idle_timeout = idle_timeout
        self._clock = clock or (lambda: datetime.now(timezone.utc))
        self._sessions: dict[str, _SessionEntry] = {}
        self._sessions_lock = asyncio.Lock()

    async def create_session(
        self,
        *,
        workflow_step: str = "created",
        application_draft: Mapping[str, Any] | None = None,
    ) -> SessionState:
        """Create a session with a unique ID generated by the server."""
        now = self._now()
        draft = validate_application_draft(application_draft)

        async with self._sessions_lock:
            session_id = secrets.token_urlsafe(32)
            while session_id in self._sessions:
                session_id = secrets.token_urlsafe(32)

            state = SessionState(
                session_id=session_id,
                workflow_step=workflow_step,
                application_draft=draft,
                status=SessionStatus.ACTIVE,
                created_at=now,
                last_activity_at=now,
                expires_at=now + self._idle_timeout,
            )
            self._sessions[session_id] = _SessionEntry(state=state)
            return self._copy_state(state)

    async def get_session(self, session_id: str) -> SessionState | None:
        """Return a copy and refresh idle expiry, or None if absent/expired."""
        entry = await self._find_entry(session_id)
        if entry is None:
            return None

        async with entry.lock:
            if not await self._is_current_entry(session_id, entry):
                return None

            now = self._now()
            if entry.state.expires_at <= now:
                await self._remove_entry(session_id, entry)
                return None

            entry.state = self._replace_state(
                entry.state,
                last_activity_at=now,
                expires_at=now + self._idle_timeout,
            )
            return self._copy_state(entry.state)

    async def update_session(
        self,
        session_id: str,
        updates: SessionUpdate,
        *,
        expected_revision: int,
    ) -> SessionState:
        """Apply a partial update only if its expected revision is current."""
        entry = await self._find_entry(session_id)
        if entry is None:
            raise SessionNotFoundError("Session was not found or has expired.")

        async with entry.lock:
            if not await self._is_current_entry(session_id, entry):
                raise SessionNotFoundError("Session was not found or has expired.")

            now = self._now()
            if entry.state.expires_at <= now:
                await self._remove_entry(session_id, entry)
                raise SessionNotFoundError("Session was not found or has expired.")
            if entry.state.revision != expected_revision:
                raise SessionConflictError("Session revision is stale.")

            old_state = entry.state
            new_draft = copy.deepcopy(old_state.application_draft)
            if updates.application_draft_patch is not None:
                new_draft.update(copy.deepcopy(updates.application_draft_patch))
                new_draft = validate_application_draft(new_draft)

            draft_changed = new_draft != old_state.application_draft
            pending = old_state.pending_confirmation
            status = old_state.status

            if draft_changed:
                pending = None
                if status == SessionStatus.AWAITING_CONFIRMATION:
                    status = SessionStatus.ACTIVE

            if updates.status is not None:
                if (
                    updates.status == SessionStatus.AWAITING_CONFIRMATION
                    and pending is None
                ):
                    raise SessionConflictError(
                        "Create a pending confirmation before changing this status."
                    )
                status = updates.status
                if status != SessionStatus.AWAITING_CONFIRMATION:
                    pending = None

            if status == SessionStatus.AWAITING_CONFIRMATION and pending is None:
                raise SessionConflictError(
                    "A pending confirmation is required for this status."
                )

            changes: dict[str, Any] = {
                "application_draft": new_draft,
                "status": status,
                "pending_confirmation": pending,
                "revision": old_state.revision + 1,
                "draft_revision": old_state.draft_revision + int(draft_changed),
                "last_activity_at": now,
                "expires_at": now + self._idle_timeout,
            }
            if updates.workflow_step is not None:
                changes["workflow_step"] = updates.workflow_step

            entry.state = self._replace_state(old_state, **changes)
            return self._copy_state(entry.state)

    async def create_pending_confirmation(
        self,
        session_id: str,
        *,
        expected_revision: int,
    ) -> SessionState:
        """Create a server-generated confirmation bound to the current draft."""
        entry = await self._find_entry(session_id)
        if entry is None:
            raise SessionNotFoundError("Session was not found or has expired.")

        async with entry.lock:
            if not await self._is_current_entry(session_id, entry):
                raise SessionNotFoundError("Session was not found or has expired.")

            now = self._now()
            if entry.state.expires_at <= now:
                await self._remove_entry(session_id, entry)
                raise SessionNotFoundError("Session was not found or has expired.")
            if entry.state.revision != expected_revision:
                raise SessionConflictError("Session revision is stale.")
            if entry.state.status != SessionStatus.ACTIVE:
                raise SessionConflictError("Session is not ready for confirmation.")

            pending = PendingConfirmation(
                confirmation_id=secrets.token_urlsafe(24),
                draft_revision=entry.state.draft_revision,
                created_at=now,
            )
            entry.state = self._replace_state(
                entry.state,
                status=SessionStatus.AWAITING_CONFIRMATION,
                pending_confirmation=pending,
                revision=entry.state.revision + 1,
                last_activity_at=now,
                expires_at=now + self._idle_timeout,
            )
            return self._copy_state(entry.state)

    async def delete_session(self, session_id: str) -> bool:
        """Delete a session and its private lock; return False if not present."""
        entry = await self._find_entry(session_id)
        if entry is None:
            return False

        async with entry.lock:
            return await self._remove_entry(session_id, entry)

    async def cleanup_expired(self) -> int:
        """Delete expired sessions and return the number of records removed."""
        async with self._sessions_lock:
            entries = list(self._sessions.items())

        now = self._now()
        removed = 0
        for session_id, entry in entries:
            async with entry.lock:
                if not await self._is_current_entry(session_id, entry):
                    continue
                if entry.state.expires_at <= now:
                    removed += int(await self._remove_entry(session_id, entry))
        return removed

    async def _find_entry(self, session_id: str) -> _SessionEntry | None:
        async with self._sessions_lock:
            return self._sessions.get(session_id)

    async def _is_current_entry(self, session_id: str, entry: _SessionEntry) -> bool:
        async with self._sessions_lock:
            return self._sessions.get(session_id) is entry

    async def _remove_entry(self, session_id: str, entry: _SessionEntry) -> bool:
        async with self._sessions_lock:
            if self._sessions.get(session_id) is not entry:
                return False
            del self._sessions[session_id]
            return True

    def _now(self) -> datetime:
        value = self._clock()
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("clock must return timezone-aware datetimes")
        return value.astimezone(timezone.utc)

    @staticmethod
    def _copy_state(state: SessionState) -> SessionState:
        return state.model_copy(deep=True)

    @staticmethod
    def _replace_state(state: SessionState, **changes: Any) -> SessionState:
        values = state.model_dump(mode="python")
        values.update(changes)
        return SessionState.model_validate(values)
